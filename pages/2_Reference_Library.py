"""Page 2 — Research Reference Library.

Displays published research with searchable metadata, study
summaries and citation information.  All content is sourced from
``research/reference_library/``.
"""

from __future__ import annotations

import sys, json
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

import streamlit as st

st.set_page_config(page_title="Reference Library — QuantumML Lab", page_icon="📚", layout="wide")

from visualization.theme import inject_custom_css, sidebar_config, page_header, COLORS, panel
from quantumml.utils import reference_library_dir

inject_custom_css()
sidebar_config()
page_header("Research Reference Library", "Published research on barren plateaus in variational quantum circuits", "📚")

# ── load references ──────────────────────────────────────────────────

ref_dir = reference_library_dir()
ref_path = ref_dir / "references.json"

if not ref_path.exists():
    st.warning("No references found.  Expected `research/reference_library/references.json`.")
    st.stop()

references = json.loads(ref_path.read_text(encoding="utf-8"))

st.info("📖 Everything in this library is from published, peer‑reviewed research.  "
        "None of these findings were generated by this project.", icon=None)

# ── search ───────────────────────────────────────────────────────────

search = st.text_input("🔍 Search papers", placeholder="e.g. barren plateau, cost function, initialization…")

filtered = references
if search:
    q = search.lower()
    filtered = [r for r in references
                if q in r.get("title", "").lower()
                or q in r.get("study_focus", "").lower()
                or q in " ".join(r.get("authors", [])).lower()
                or q in r.get("reported_finding", "").lower()]

if not filtered:
    st.markdown(f'<p style="color:{COLORS["text_muted"]};">No papers match your search.</p>',
                unsafe_allow_html=True)
    st.stop()

st.caption(f"Showing {len(filtered)} of {len(references)} papers")

# ── paper cards ──────────────────────────────────────────────────────

for ref in filtered:
    with st.expander(f"**{ref.get('year', '')}** — {ref.get('title', 'Untitled')}"):
        c1, c2 = st.columns([2, 1])
        with c1:
            authors = ", ".join(ref.get("authors", []))
            st.markdown(f"**Authors:** {authors}")
            venue = ref.get("venue", "")
            vol = ref.get("volume", "")
            art = ref.get("article", "")
            st.markdown(f"**Venue:** {venue}, vol. {vol}, art. {art}" if vol else f"**Venue:** {venue}")
            doi = ref.get("doi", "")
            if doi:
                st.markdown(f"**DOI:** [{doi}](https://doi.org/{doi})")
            url = ref.get("url", "")
            if url:
                st.markdown(f"[Open publisher page]({url})")
        with c2:
            st.markdown(f"""
            <div class="ql-panel" style="padding:0.8rem;">
                <span class="ql-muted ql-small" style="font-weight:600;">SOURCE CLASSIFICATION</span><br>
                <span style="color:{COLORS['accent']}; font-weight:600;">
                    {ref.get('source_type', 'PUBLISHED_REFERENCE')}
                </span>
            </div>
            """, unsafe_allow_html=True)

        st.markdown(f"**Study focus:** {ref.get('study_focus', 'N/A')}")
        st.markdown(f"**Reported finding:** {ref.get('reported_finding', 'N/A')}")
        st.warning(f"⚠️ **Comparison note:** {ref.get('limitations_for_comparison', 'N/A')}")

# ── reading notes ────────────────────────────────────────────────────

st.markdown("---")
st.markdown("### Study Notes")
notes_path = ref_dir / "published_findings" / "reading_notes.md"
if notes_path.exists():
    st.markdown(notes_path.read_text(encoding="utf-8"))
else:
    st.caption("No reading notes found.")

st.markdown("---")
st.markdown("### Research Integrity Rules")
panel(
    "<ol style='margin:0; padding-left:1.2rem; color:" + COLORS["text_muted"] + "; font-size:0.85rem;'>"
    "<li>Read the paper before citing a specific result.</li>"
    "<li>Do not copy numbers from abstracts as full datasets.</li>"
    "<li>Store exact published values only with page/figure/table locators.</li>"
    "<li>Mark unreported values as <em>Not reported</em>.</li>"
    "<li>Keep all project‑generated data outside this directory.</li>"
    "</ol>",
    COLORS["accent2"],
)
